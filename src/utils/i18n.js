export function getAppLanguage() {
  const stored = storage.get(STORAGE_KEYS.APP_LANGUAGE);
  if (stored === "en" || stored === "es") return stored;
  const system =
    typeof navigator !== "undefined" ? String(navigator.language || "") : "";
  return system.toLowerCase().startsWith("es") ? "es" : "en";
}

export function setAppLanguage(language) {
  const next = language === "en" ? "en" : "es";
  storage.set(STORAGE_KEYS.APP_LANGUAGE, next);
  if (typeof document !== "undefined") {
    document.documentElement.setAttribute("lang", next);
  }
  if (typeof window !== "undefined") {
    window.dispatchEvent(
      new CustomEvent(LANGUAGE_EVENT, { detail: next }),
    );
  }
  return next;
}

export function translate(key, vars, language = getAppLanguage()) {
  const table = MESSAGES[language] || MESSAGES.es;
  let value = table[key] ?? MESSAGES.es[key] ?? key;
  if (vars && typeof value === "string") {
    for (const [name, replacement] of Object.entries(vars)) {
      value = value.replaceAll(`{${name}}`, String(replacement));
    }
  }
  return value;
}

export function useAppLanguage() {
  const [language, setLanguage] = useState(getAppLanguage);
  useEffect(() => {
    const handler = (event) =>
      setLanguage(event.detail === "en" ? "en" : "es");
    window.addEventListener(LANGUAGE_EVENT, handler);
    return () => window.removeEventListener(LANGUAGE_EVENT, handler);
  }, []);
  return language;
}

export function useT() {
  const language = useAppLanguage();
  return useCallback(
    (key, vars) => translate(key, vars, language),
    [language],
  );
}
